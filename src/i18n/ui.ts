const IDX: Record<Lang, number> = { ar: 0, en: 1, fr: 2 };

export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  const e = S[key];
  let s = e ? e[IDX[lang]] || e[1] : key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''));
  return s;
}

